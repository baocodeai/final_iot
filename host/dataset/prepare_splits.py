"""Create deterministic, stratified CIFAR-10 split manifests.

The project proposal requires exact per-class counts:
- train: 4,500 images/class = 45,000
- validation: 500 images/class = 5,000
- calibration: 50 images/class = 500
- validation_bitrate: 50 images/class = 500
- hardware_test: 2 images/class, generated by prepare_cifar10.py
"""

from __future__ import annotations

import csv
import hashlib
import json
import pickle
import tarfile
from collections import Counter
from pathlib import Path

import numpy as np


SEED = 2026
TRAIN_PER_CLASS = 4_500
VALIDATION_PER_CLASS = 500
CALIBRATION_PER_CLASS = 50
VALIDATION_BITRATE_PER_CLASS = 50
TEST_SIZE = 10_000

PROJECT_ROOT = Path(__file__).resolve().parents[2]
ARCHIVE_PATH = PROJECT_ROOT / "data" / "raw" / "cifar-10-python.tar.gz"
OUTPUT_DIR = PROJECT_ROOT / "data" / "splits"
NPZ_PATH = OUTPUT_DIR / "cifar10_seed2026_indices.npz"
JSON_PATH = OUTPUT_DIR / "cifar10_seed2026_manifest.json"

CLASS_NAMES = (
    "airplane",
    "automobile",
    "bird",
    "cat",
    "deer",
    "dog",
    "frog",
    "horse",
    "ship",
    "truck",
)


def sha256_indices(indices: np.ndarray) -> str:
    return hashlib.sha256(indices.astype("<i4").tobytes()).hexdigest()


def load_train_labels() -> np.ndarray:
    labels: list[int] = []
    with tarfile.open(ARCHIVE_PATH, mode="r:gz") as archive:
        for batch_id in range(1, 6):
            member_name = f"cifar-10-batches-py/data_batch_{batch_id}"
            member = archive.getmember(member_name)
            extracted = archive.extractfile(member)
            if extracted is None:
                raise RuntimeError(f"Could not read {member_name}")
            batch = pickle.load(extracted, encoding="bytes")
            labels.extend(int(label) for label in batch[b"labels"])

    label_array = np.asarray(labels, dtype=np.int64)
    if label_array.shape != (50_000,):
        raise RuntimeError(f"Unexpected CIFAR-10 train label shape: {label_array.shape}")
    return label_array


def load_test_labels() -> np.ndarray:
    member_name = "cifar-10-batches-py/test_batch"
    with tarfile.open(ARCHIVE_PATH, mode="r:gz") as archive:
        member = archive.getmember(member_name)
        extracted = archive.extractfile(member)
        if extracted is None:
            raise RuntimeError(f"Could not read {member_name}")
        batch = pickle.load(extracted, encoding="bytes")

    labels = np.asarray(batch[b"labels"], dtype=np.int64)
    if labels.shape != (TEST_SIZE,):
        raise RuntimeError(f"Unexpected CIFAR-10 test label shape: {labels.shape}")
    return labels


def stratified_train_validation_split(labels: np.ndarray) -> dict[str, np.ndarray]:
    rng = np.random.default_rng(SEED)
    train_parts: list[np.ndarray] = []
    validation_parts: list[np.ndarray] = []
    calibration_parts: list[np.ndarray] = []
    validation_bitrate_parts: list[np.ndarray] = []

    for class_id in range(len(CLASS_NAMES)):
        class_indices = np.flatnonzero(labels == class_id).astype(np.int32)
        if len(class_indices) != TRAIN_PER_CLASS + VALIDATION_PER_CLASS:
            raise RuntimeError(
                f"Class {class_id} has {len(class_indices)} train images, expected 5000"
            )

        shuffled = rng.permutation(class_indices).astype(np.int32)
        train_class = shuffled[:TRAIN_PER_CLASS]
        validation_class = shuffled[TRAIN_PER_CLASS:]

        train_parts.append(train_class)
        validation_parts.append(validation_class)
        calibration_parts.append(train_class[:CALIBRATION_PER_CLASS].copy())
        validation_bitrate_parts.append(
            validation_class[:VALIDATION_BITRATE_PER_CLASS].copy()
        )

    return {
        "train": rng.permutation(np.concatenate(train_parts)).astype(np.int32),
        "validation": rng.permutation(np.concatenate(validation_parts)).astype(np.int32),
        "calibration": rng.permutation(np.concatenate(calibration_parts)).astype(
            np.int32
        ),
        "validation_bitrate": rng.permutation(
            np.concatenate(validation_bitrate_parts)
        ).astype(np.int32),
    }


def class_counts(indices: np.ndarray, labels: np.ndarray) -> dict[str, int]:
    counts = Counter(int(labels[int(index)]) for index in indices)
    return {CLASS_NAMES[class_id]: int(counts[class_id]) for class_id in range(10)}


def write_csv_manifest(
    name: str, indices: np.ndarray, labels: np.ndarray, index_space: str
) -> str:
    path = OUTPUT_DIR / f"{name}_manifest.csv"
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(
            stream,
            fieldnames=("split", "index_space", "index", "class_id", "class_name"),
        )
        writer.writeheader()
        for index in indices:
            class_id = int(labels[int(index)])
            writer.writerow(
                {
                    "split": name,
                    "index_space": index_space,
                    "index": int(index),
                    "class_id": class_id,
                    "class_name": CLASS_NAMES[class_id],
                }
            )
    return path.relative_to(PROJECT_ROOT).as_posix()


def validate_splits(splits: dict[str, np.ndarray], labels: np.ndarray) -> None:
    train_indices = splits["train"]
    validation_indices = splits["validation"]
    calibration_indices = splits["calibration"]
    validation_bitrate_indices = splits["validation_bitrate"]

    assert len(train_indices) == TRAIN_PER_CLASS * len(CLASS_NAMES)
    assert len(validation_indices) == VALIDATION_PER_CLASS * len(CLASS_NAMES)
    assert len(calibration_indices) == CALIBRATION_PER_CLASS * len(CLASS_NAMES)
    assert len(validation_bitrate_indices) == (
        VALIDATION_BITRATE_PER_CLASS * len(CLASS_NAMES)
    )
    assert len(np.intersect1d(train_indices, validation_indices)) == 0
    assert np.array_equal(
        np.sort(np.concatenate((train_indices, validation_indices))),
        np.arange(50_000),
    )
    assert np.all(np.isin(calibration_indices, train_indices))
    assert np.all(np.isin(validation_bitrate_indices, validation_indices))

    expected_counts = {
        "train": TRAIN_PER_CLASS,
        "validation": VALIDATION_PER_CLASS,
        "calibration": CALIBRATION_PER_CLASS,
        "validation_bitrate": VALIDATION_BITRATE_PER_CLASS,
    }
    for split_name, expected_count in expected_counts.items():
        counts = class_counts(splits[split_name], labels)
        if any(count != expected_count for count in counts.values()):
            raise RuntimeError(f"{split_name} class counts are not stratified: {counts}")


def main() -> None:
    if not ARCHIVE_PATH.exists():
        raise FileNotFoundError(
            f"Missing CIFAR-10 archive: {ARCHIVE_PATH}. Run prepare_cifar10.py first."
        )

    train_labels = load_train_labels()
    test_labels = load_test_labels()
    splits = stratified_train_validation_split(train_labels)
    splits["test"] = np.arange(TEST_SIZE, dtype=np.int32)

    validate_splits(splits, train_labels)

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(
        NPZ_PATH,
        train_indices=splits["train"],
        validation_indices=splits["validation"],
        calibration_indices=splits["calibration"],
        validation_bitrate_indices=splits["validation_bitrate"],
        test_indices=splits["test"],
    )

    csv_files = {
        name: write_csv_manifest(
            name,
            indices,
            train_labels if name != "test" else test_labels,
            "original_train" if name != "test" else "original_test",
        )
        for name, indices in splits.items()
    }

    set_metadata = {}
    for name, indices in splits.items():
        labels = train_labels if name != "test" else test_labels
        set_metadata[name] = {
            "count": int(len(indices)),
            "index_space": "original_train" if name != "test" else "original_test",
            "indices_sha256_int32_le": sha256_indices(indices),
            "class_counts": class_counts(indices, labels),
            "csv_manifest": csv_files[name],
        }

    manifest = {
        "dataset": "CIFAR-10 Python version",
        "seed": SEED,
        "policy": (
            "Deterministic stratified split by CIFAR-10 class. For each class, "
            "4500 original training images are assigned to train and 500 to "
            "validation. Calibration uses 50 train images per class. "
            "Validation-bitrate uses 50 validation images per class. Test uses "
            "the full official 10000-image CIFAR-10 test batch."
        ),
        "proposal_requirements": {
            "train_per_class": TRAIN_PER_CLASS,
            "validation_per_class": VALIDATION_PER_CLASS,
            "calibration_per_class": CALIBRATION_PER_CLASS,
            "validation_bitrate_per_class": VALIDATION_BITRATE_PER_CLASS,
            "hardware_test_per_class": 2,
        },
        "sets": set_metadata,
        "indices_file": NPZ_PATH.relative_to(PROJECT_ROOT).as_posix(),
    }
    JSON_PATH.write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8"
    )

    print(f"Created: {NPZ_PATH}")
    print(f"Created: {JSON_PATH}")
    for name, metadata in set_metadata.items():
        print(f"{name}: {metadata['count']} indices")
        print(f"  SHA256={metadata['indices_sha256_int32_le']}")
        print(f"  class_counts={metadata['class_counts']}")
        print(f"  csv={metadata['csv_manifest']}")


if __name__ == "__main__":
    main()
